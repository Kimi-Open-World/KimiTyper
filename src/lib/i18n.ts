type TranslationKey = keyof typeof translations['zh']

export function t(key: TranslationKey, lang: Language, vars?: Record<string, string | number>): string {
    const str = translations[lang]?.[key] ?? translations['zh'][key] ?? key
    if (!vars) return str
    return Object.entries(vars).reduce((s, [k, v]) => s.replace(`{${k}}`, String(v)), str)
}

export function createT(lang: Language) {
    return (key: TranslationKey, vars?: Record<string, string | number>) => t(key, lang, vars)
}
